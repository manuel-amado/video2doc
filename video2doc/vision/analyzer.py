"""Multimodal vision analysis module querying local Vision LLMs via Ollama."""

from __future__ import annotations

import base64
import logging
from pathlib import Path
from typing import Any

import requests

from video2doc.config import Settings, get_settings
from video2doc.exceptions import MediaCorruptError, ModelNotFoundError, OllamaConnectionError
from video2doc.vision.keyframes import Keyframe

logger = logging.getLogger(__name__)


class VisionAnalyzer:
    """Analyzes visual keyframes using local multimodal LLMs via Ollama `/api/chat`."""

    def __init__(
        self,
        settings: Settings | None = None,
        model_name: str | None = None,
        timeout_seconds: float | None = None,
    ) -> None:
        self.settings = settings or get_settings()
        self.model_name = model_name or self.settings.vision_model
        self.timeout = (
            timeout_seconds if timeout_seconds is not None else self.settings.timeout_seconds
        )

    def _encode_image(self, image_path: Path | str) -> str:
        """Encode a keyframe image file into raw Base64 string without data URI prefix."""
        path = Path(image_path)
        if not path.exists():
            raise MediaCorruptError(str(path), reason="Keyframe image file does not exist.")
        if path.is_file() and path.stat().st_size == 0:
            raise MediaCorruptError(str(path), reason="Keyframe image file is empty (0 bytes).")

        try:
            image_bytes = path.read_bytes()
            if not image_bytes:
                raise MediaCorruptError(str(path), reason="Keyframe image file contains no data.")
            return base64.b64encode(image_bytes).decode("utf-8")
        except OSError as err:
            raise MediaCorruptError(
                str(path),
                reason=f"Failed to read image file: {err}",
            ) from err

    def analyze_frame(
        self,
        frame: Keyframe | Path | str,
        prompt: str = "Describe the keyframe image in detail.",
    ) -> str:
        """Analyze a single keyframe image and return structured description text.

        Args:
            frame: A Keyframe instance or Path/string pointing to an image file.
            prompt: Domain-specific prompt instructing visual analysis.

        Returns:
            Description text generated by the vision model.
        """
        frame_path = frame.frame_path if isinstance(frame, Keyframe) else Path(frame)
        base64_image = self._encode_image(frame_path)

        url = f"{self.settings.ollama_url.rstrip('/')}/api/chat"
        payload: dict[str, Any] = {
            "model": self.model_name,
            "messages": [
                {
                    "role": "user",
                    "content": prompt,
                    "images": [base64_image],
                }
            ],
            "stream": False,
            "options": {
                "temperature": self.settings.model_temperature,
            },
        }

        try:
            resp = requests.post(url, json=payload, timeout=self.timeout)
        except requests.exceptions.RequestException as err:
            raise OllamaConnectionError(
                self.settings.ollama_url,
                reason=f"Network request to Ollama failed: {err}",
            ) from err

        if resp.status_code == 404:
            try:
                err_body = resp.json()
                err_msg = err_body.get("error", resp.text)
            except Exception:
                err_msg = resp.text
            raise ModelNotFoundError(
                self.model_name,
                message=f"Vision model '{self.model_name}' not found on Ollama: {err_msg}",
            )

        if not resp.ok:
            raise OllamaConnectionError(
                self.settings.ollama_url,
                reason=f"HTTP {resp.status_code}: {resp.text}",
            )

        try:
            data = resp.json()
        except Exception as err:
            raise OllamaConnectionError(
                self.settings.ollama_url,
                reason=f"Ollama returned malformed JSON response: {err}",
            ) from err

        if "error" in data and "not found" in str(data["error"]).lower():
            raise ModelNotFoundError(self.model_name, message=str(data["error"]))

        msg = data.get("message", {})
        if isinstance(msg, dict):
            content = msg.get("content", "")
        else:
            content = ""

        if not content:
            content = data.get("response", "")

        return str(content).strip()

    def analyze_all(
        self,
        keyframes: list[Keyframe],
        prompt: str = "Describe the keyframe image in detail.",
    ) -> list[str]:
        """Analyze a list of keyframes chronologically and return a list of descriptions.

        Args:
            keyframes: List of Keyframe objects.
            prompt: Vision prompt instruction.

        Returns:
            List of text descriptions corresponding to keyframes.
        """
        descriptions: list[str] = []
        for kf in keyframes:
            desc = self.analyze_frame(kf, prompt=prompt)
            descriptions.append(desc)
        return descriptions

    def analyze_keyframes(
        self,
        keyframes: list[Keyframe],
        template: Any = None,
    ) -> list[dict[str, Any]]:
        """Analyze keyframes using template vision prompt, returning structured metadata.

        Args:
            keyframes: List of Keyframe objects.
            template: Optional TemplateDefinition instance or custom prompt string.

        Returns:
            List of dictionaries containing timestamp, frame_path, description, and score.
        """
        if template is not None and hasattr(template, "vision_prompt") and template.vision_prompt:
            prompt = str(template.vision_prompt).strip()
        elif isinstance(template, str) and template.strip():
            prompt = template.strip()
        else:
            prompt = (
                "Describe the keyframe image in detail, noting visible UI controls, "
                "text, diagrams, and user actions."
            )

        results: list[dict[str, Any]] = []
        for kf in keyframes:
            desc = self.analyze_frame(kf, prompt=prompt)
            results.append({
                "timestamp": kf.timestamp,
                "frame_path": Path(kf.frame_path),
                "description": desc,
                "score": getattr(kf, "score", 0.0),
            })
        return results
